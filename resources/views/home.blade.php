// ── SCROLL REVEAL ──
const observer = new IntersectionObserver((entries) => {
  entries.forEach(e => {
    if(e.isIntersecting){ e.target.classList.add('visible'); }
  });
},{threshold:0.12});
document.querySelectorAll('.reveal,.reveal-left,.reveal-right,.reveal-scale').forEach(el => observer.observe(el));
 
// ── FAQ ──
document.querySelectorAll('.faq-q').forEach(q => {
  q.addEventListener('click',()=>{
    const item = q.parentElement;
    document.querySelectorAll('.faq-item.open').forEach(o=>{ if(o!==item) o.classList.remove('open'); });
    item.classList.toggle('open');
  });
});
 
// ── ACTIVE NAV ──
const secs = document.querySelectorAll('section[id]');
const navAs = document.querySelectorAll('nav a');
window.addEventListener('scroll',()=>{
  let cur='';
  secs.forEach(s=>{ if(window.scrollY>=s.offsetTop-80) cur=s.id; });
  navAs.forEach(a=>{ a.classList.remove('active'); if(a.getAttribute('href')==='#'+cur) a.classList.add('active'); });
});
 
// ── SMOOTH SCROLL ──
document.querySelectorAll('a[href^="#"]').forEach(a=>{
  a.addEventListener('click',e=>{
    const t = document.querySelector(a.getAttribute('href'));
    if(t){e.preventDefault();t.scrollIntoView({behavior:'smooth'});}
  });
});
 
